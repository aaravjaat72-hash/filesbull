-- filesbull / universal Telegram file bot — ONE-TIME DATABASE SETUP (Supabase → SQL Editor → New query → paste → Run)
-- Safe to run again any time (everything is "if not exists"). The bot can also run this itself when the
-- optional Vercel variable SUPABASE_ACCESS_TOKEN is set. Same text as SETUP_SQL in app.py.

create table if not exists public.channels (
  id bigint generated by default as identity primary key,
  chat_id bigint not null unique,
  title text not null,
  username text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.required_channels (
  id bigint generated by default as identity primary key,
  chat_id bigint not null unique,
  title text not null,
  username text,
  invite_link text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.admins (
  user_id bigint primary key,
  role text not null default 'subadmin',
  can_manage_files boolean not null default true,
  can_manage_channels boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.bot_settings (
  key text primary key,
  value text,
  updated_at timestamptz not null default now()
);

create table if not exists public.books (
  id bigint generated by default as identity primary key,
  source_chat_id bigint not null,
  source_chat_title text,
  source_chat_username text,
  source_message_id bigint not null,
  source_link text,
  telegram_file_id text,
  telegram_file_unique_id text unique,
  file_name text,
  mime_type text,
  file_size bigint,
  title text not null,
  caption text,
  keywords text,
  content_text text,
  language text,
  status text not null default 'indexed',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists books_title_idx on public.books(title);
create index if not exists books_keywords_idx on public.books(keywords);
create index if not exists books_source_chat_idx on public.books(source_chat_id);

alter table public.books add column if not exists content_text text;
alter table public.books add column if not exists backup_chat_id bigint;
alter table public.books add column if not exists backup_message_id bigint;

create table if not exists public.delivery_logs (
  id bigint generated by default as identity primary key,
  user_id bigint,
  username text,
  query text,
  book_id bigint,
  book_title text,
  created_at timestamptz not null default now()
);

alter table public.channels enable row level security;
alter table public.books enable row level security;
alter table public.required_channels enable row level security;
alter table public.admins enable row level security;
alter table public.bot_settings enable row level security;
alter table public.delivery_logs enable row level security;

-- The server uses the Supabase service-role key and does not expose these tables directly to users.
-- Never put SUPABASE_SERVICE_ROLE_KEY in browser/client code.

-- ---- users table + delivery log columns (was migrate_users.sql)
create table if not exists public.bot_users (
  user_id bigint primary key,
  first_name text,
  last_name text,
  username text,
  first_seen timestamptz not null default now(),
  last_seen timestamptz not null default now(),
  verified boolean not null default false,
  searches integer not null default 0,
  files_received integer not null default 0
);
create index if not exists bot_users_last_seen_idx on public.bot_users (last_seen desc);
create index if not exists bot_users_first_seen_idx on public.bot_users (first_seen desc);
alter table public.bot_users enable row level security;

-- delivery log: who got which file, for which search
alter table public.delivery_logs add column if not exists username text;
alter table public.delivery_logs add column if not exists query text;
create index if not exists delivery_logs_user_idx on public.delivery_logs (user_id, created_at desc);
create index if not exists delivery_logs_created_idx on public.delivery_logs (created_at desc);

-- backup: find files not yet copied to the backup channel quickly
create index if not exists books_backup_msg_idx on public.books (backup_message_id);

-- ---- subject category column (was migrate_category.sql)
alter table public.books add column if not exists category text;
create index if not exists books_category_idx on public.books (category);
