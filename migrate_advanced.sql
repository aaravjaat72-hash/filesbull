alter table public.books add column if not exists content_text text;
alter table public.books add column if not exists backup_chat_id bigint;
alter table public.books add column if not exists backup_message_id bigint;

create table if not exists public.required_channels (
  id bigint generated by default as identity primary key,
  chat_id bigint not null unique,
  title text not null,
  username text,
  invite_link text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.admins (
  user_id bigint primary key,
  role text not null default 'subadmin',
  can_manage_files boolean not null default true,
  can_manage_channels boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.bot_settings (
  key text primary key,
  value text,
  updated_at timestamptz not null default now()
);

create table if not exists public.delivery_logs (
  id bigint generated by default as identity primary key,
  user_id bigint,
  username text,
  query text,
  book_id bigint,
  book_title text,
  created_at timestamptz not null default now()
);

