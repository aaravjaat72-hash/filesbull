create table if not exists public.channels (
  id bigint generated by default as identity primary key,
  chat_id bigint not null unique,
  title text not null,
  username text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.books (
  id bigint generated by default as identity primary key,
  source_chat_id bigint not null,
  source_chat_title text,
  source_chat_username text,
  source_message_id bigint not null,
  source_link text,
  telegram_file_id text,
  telegram_file_unique_id text unique,
  file_name text,
  mime_type text,
  file_size bigint,
  title text not null,
  caption text,
  keywords text,
  language text,
  status text not null default 'indexed',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists books_title_idx on public.books(title);
create index if not exists books_keywords_idx on public.books(keywords);
create index if not exists books_source_chat_idx on public.books(source_chat_id);

alter table public.channels enable row level security;
alter table public.books enable row level security;

-- The server uses the Supabase service-role key and does not expose these tables directly to users.
